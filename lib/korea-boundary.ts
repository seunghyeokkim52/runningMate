function isWithinRing(
  { lat, lng }: Coordinates,
  ring: [number, number][]
): boolean {
  let inside = false;

  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];

    const intersects =
      yi > lat !== yj > lat &&
      lng < ((xj - xi) * (lat - yi)) / (yj - yi) + xi;

    if (intersects) inside = !inside;
  }

  return inside;
}

/** Ray casting 알고리즘으로 점이 대한민국 국경(본토·제주·도서 포함) 안에 있는지 판단한다. */
export function isWithinSouthKorea(coords: Coordinates): boolean {
  return SOUTH_KOREA_BOUNDARY.some((ring) => isWithinRing(coords, ring));
}
